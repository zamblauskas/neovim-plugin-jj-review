local assert = require("luassert")
local helpers = require("tests.helpers")
local jj = require("review.shell.jj")

describe("jj port", function()
  local repo

  before_each(function()
    repo = helpers.temp_repo()
  end)

  it("finds the repo root", function()
    local result = helpers.run_async(function()
      return jj.root(repo)
    end)
    assert.is_true(result.ok)
    assert.are.same(repo, vim.trim(result.stdout))
  end)

  it("reads the operation id", function()
    local result = helpers.run_async(function()
      return jj.op_id(repo)
    end)
    assert.is_true(result.ok)
    assert.truthy(result.stdout:match("^%x+$"))
  end)

  it("does not snapshot the working copy", function()
    local before = helpers.run_async(function()
      return jj.op_id(repo).stdout
    end)
    vim.fn.writefile({ "new" }, repo .. "/file.txt")
    local after = helpers.run_async(function()
      jj.log(repo, "@", "commit_id")
      return jj.op_id(repo).stdout
    end)
    assert.are.same(before, after)
  end)

  it("reads the git diff of a revision", function()
    vim.fn.writefile({ "a" }, repo .. "/file.txt")
    helpers.jj(repo, { "util", "snapshot" })
    local result = helpers.run_async(function()
      return jj.diff(repo, "@")
    end)
    assert.is_true(result.ok)
    assert.truthy(result.stdout:find("diff --git a/file.txt b/file.txt", 1, true))
  end)

  it("shows a file whose name has a quote, a backslash and a space", function()
    local name = 'q"t \\x.txt'
    vim.fn.writefile({ "content" }, repo .. "/" .. name)
    helpers.jj(repo, { "util", "snapshot" })
    local result = helpers.run_async(function()
      return jj.file_show(repo, "@", name)
    end)
    assert.are.same({ true, "content\n" }, { result.ok, result.stdout })
  end)

  it("snapshots the working copy: a new operation", function()
    local before = helpers.run_async(function()
      return jj.op_id(repo).stdout
    end)
    vim.fn.writefile({ "new" }, repo .. "/file.txt")
    local after = helpers.run_async(function()
      assert(jj.snapshot(repo).ok)
      return jj.op_id(repo).stdout
    end)
    assert.are_not.same(before, after)
  end)

  it("makes a revision the working copy", function()
    helpers.jj(repo, { "describe", "-m", "first" })
    local change_id = vim.trim(helpers.jj(repo, { "log", "-r", "@", "--no-graph", "-T", "change_id" }))
    helpers.jj(repo, { "new" })
    local result = helpers.run_async(function()
      return jj.edit(repo, change_id)
    end)
    assert.is_true(result.ok)
    assert.are.same(change_id, vim.trim(helpers.jj(repo, { "log", "-r", "@", "--no-graph", "-T", "change_id" })))
  end)

  it("returns stderr when the command fails", function()
    local result = helpers.run_async(function()
      return jj.log(repo, "no_such_revision", "commit_id")
    end)
    assert.is_false(result.ok)
    assert.truthy(result.stderr:find("no_such_revision"))
  end)

  it("fails outside a repo", function()
    local result = helpers.run_async(function()
      return jj.root(vim.fn.fnamemodify(repo, ":h"))
    end)
    assert.is_false(result.ok)
  end)
end)
