local assert = require("luassert")
local async = require("review.shell.lib.async")
local helpers = require("tests.helpers")

describe("async", function()
  it("returns values from an asynchronous callback", function()
    local a, b = helpers.run_async(function()
      return async.await(function(done)
        vim.schedule(function()
          done(1, nil)
        end)
      end)
    end)
    assert.are.same({ 1, nil }, { a, b })
  end)

  it("returns values from a synchronous callback", function()
    local value = helpers.run_async(function()
      return async.await(function(done)
        done("now")
      end)
    end)
    assert.are.same("now", value)
  end)

  it("runs steps in order", function()
    local steps = helpers.run_async(function()
      local first = async.await(function(done)
        vim.schedule(function()
          done("a")
        end)
      end)
      local second = async.await(function(done)
        done("b")
      end)
      return { first, second }
    end)
    assert.are.same({ "a", "b" }, steps)
  end)

  it("reports errors to on_error", function()
    local reported
    async.run(function()
      error("boom")
    end, function(err)
      reported = err
    end)
    assert.truthy(reported:find("boom"))
  end)

  it("fails when await is called outside run", function()
    assert.has_error(function()
      async.await(function() end)
    end)
  end)
end)
